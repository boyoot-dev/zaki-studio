// Keeps src/shared/format in step with the app's shared files (task 163). The public Studio
// repository is built from studio/ alone and has no ../app beside it, so the files it shares
// with the Mr. Zaki app are copies, made here and checked by src/shared/format-sync.test.ts
// when this is the monorepo. Run this after the app's copies change:
//
//   npm run sync-format
//
// The copies are the app's files, byte for byte apart from their first two lines and their
// imports, which are rewritten to point inside format/. Nothing here is edited by hand: an
// edit made in the copy fails the sync test, and an app file that no longer copies cleanly
// fails this script.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/** The Studio folder: this file's folder is studio/scripts. */
const STUDIO = fileURLToPath(new URL("..", import.meta.url));

/** The app folder beside it. In the public repository it is not there, and syncing stops. */
const APP = join(STUDIO, "..", "app");

/** The files copied, as [path inside app/, path inside src/shared/format]. */
const FILES = [
	["src/lib/bundle.ts", "bundle.ts"],
	["src/lib/grades.ts", "grades.ts"],
	["src/lib/web-address.ts", "web-address.ts"],
	["content/curriculum/subjects.json", "subjects.json"],
] as const;

/** The two lines every copy starts with: where it comes from, and that it is not edited here. */
export function header(from: string): string {
	return `// Copied from app/${from} by scripts/sync-format.ts: do not edit this file here.\n// Run "npm run sync-format" in studio/ to update it from the app.\n`;
}

/** Every specifier a source file imports, through `from`, `import()` or a side effect. */
function specifiersOf(source: string): string[] {
	const found: string[] = [];
	for (const pattern of [
		/\bfrom\s*["']([^"']+)["']/g,
		/\bimport\s*\(\s*["']([^"']+)["']\s*\)/g,
		/^\s*import\s+["']([^"']+)["']/gm,
	]) {
		for (const match of source.matchAll(pattern)) {
			if (match[1] !== undefined) found.push(match[1]);
		}
	}
	return found;
}

/** The copied app file a relative specifier points at, as its target name, or null. */
function copiedImport(
	appRoot: string,
	fromFile: string,
	specifier: string,
): string | null {
	const base = resolve(dirname(fromFile), specifier);
	for (const [from, to] of FILES) {
		const appFile = join(appRoot, from);
		for (const candidate of [base, `${base}.ts`, `${base}.tsx`]) {
			if (candidate === appFile) return to;
		}
	}
	return null;
}

/** An app file's text with its imports pointed inside format/. Throws on any other import. */
export function rewritten(
	appRoot: string,
	from: string,
	source: string,
): string {
	if (from.endsWith(".json")) return source;
	const fromFile = join(appRoot, from);
	let out = source;
	for (const specifier of new Set(specifiersOf(source))) {
		if (specifier.startsWith("node:")) continue;
		const to = copiedImport(appRoot, fromFile, specifier);
		if (to === null)
			throw new Error(
				`${from} imports "${specifier}", which is not one of the copied files: copy it too, or keep the app's file self-contained`,
			);
		out = out.split(`"${specifier}"`).join(`"./${to.replace(/\.tsx?$/, "")}"`);
		out = out.split(`'${specifier}'`).join(`'./${to.replace(/\.tsx?$/, "")}'`);
	}
	return out;
}

/** What the copies must hold, without writing them: for the sync test and for main. */
export function expectedCopies(
	appRoot: string,
): { to: string; content: string }[] {
	return FILES.map(([from, to]) => {
		const source = readFileSync(join(appRoot, from), "utf8");
		return {
			to: join(STUDIO, "src", "shared", "format", to),
			content: header(from) + rewritten(appRoot, from, source),
		};
	});
}

function main(): void {
	if (!existsSync(join(APP, "src", "lib", "bundle.ts"))) {
		console.error(
			"../app is not beside this repository: the format copies are kept in step by the app's own repository",
		);
		process.exitCode = 2;
		return;
	}
	const format = join(STUDIO, "src", "shared", "format");
	mkdirSync(format, { recursive: true });
	for (const { to, content } of expectedCopies(APP)) {
		writeFileSync(to, content, "utf8");
		console.log(`copied ${relative(STUDIO, to)}`);
	}
}

if (process.argv[1]?.endsWith("sync-format.ts") === true) main();
